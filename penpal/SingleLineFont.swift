    // Helper to create CGPoint more concisely
    private static func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint {
        CGPoint(x: x, y: y)
    }

    // Get strokes for a character with optional variation
    static func strokes(for char: Character, variation: Int = 0) -> [[CGPoint]] {
        // Check lowercase first, then uppercase, then numbers, then punctuation
        if let strokes = lowercase[char] {
            return applyVariation(strokes, seed: variation)
        }
        if let strokes = uppercase[char] {
            return applyVariation(strokes, seed: variation)
        }
        if let strokes = lowercase[Character(char.lowercased())] {
            return applyVariation(strokes, seed: variation)
        }
        if let strokes = numbers[char] {
            return applyVariation(strokes, seed: variation)
        }
        if let strokes = punctuation[char] {
            return applyVariation(strokes, seed: variation)
        }
        return []
    }

    // Apply subtle random variation to strokes for more natural look
    private static func applyVariation(_ strokes: [[CGPoint]], seed: Int) -> [[CGPoint]] {
        return strokes.map { stroke in
            stroke.enumerated().map { (index, point) in
                let variationX = CGFloat(sin(Double(seed + index) * 0.7)) * 0.02
                let variationY = CGFloat(cos(Double(seed + index) * 1.1)) * 0.02
                return CGPoint(x: point.x + variationX, y: point.y + variationY)
            }
        }
    }
